  await audit(page, 'Mobile saved receipt')
  await page.screenshot({ path: testInfo.outputPath('mobile-receipt.png') })
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  for (const name of ['Coordinator', 'Tanker driver', 'Maintenance crew']) {
    await role(page, name)
    for (const width of [320, 390, 768, 1024, 1440]) {
      await page.setViewportSize({ width, height: 960 })
      await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), { message: `${name} at ${width}px` }).toBe(true)
    }
    await page.setViewportSize({ width: 390, height: 844 })
    await audit(page, `${name} mobile workspace`)
  }
  expect(errors).toEqual([])
  await context.close()

  const fallback = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' })
  await fallback.addInitScript(() => { const original = HTMLCanvasElement.prototype.getContext; HTMLCanvasElement.prototype.getContext = function (this: HTMLCanvasElement, type: string, options?: unknown) { return /webgl/i.test(type) ? null : Reflect.apply(original, this, [type, options]) } as typeof original })
  const noGL = await fallback.newPage(); await noGL.goto('/')
  await expect(noGL.locator('.world-map-alternative')).toBeVisible()
  await noGL.getByRole('button', { name: 'Report a water issue', exact: true }).click()
