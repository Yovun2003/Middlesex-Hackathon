test('committed revision events update another coordinator session without exposing report data', async ({ browser }) => {
  const residentContext = await browser.newContext({ reducedMotion: 'reduce' })
  const coordinatorContext = await browser.newContext({ reducedMotion: 'reduce' })
  const resident = await residentContext.newPage(); const coordinator = await coordinatorContext.newPage()
  await resident.goto('/'); await role(resident, 'Resident')
  await coordinator.goto('/'); await role(coordinator, 'Coordinator')
  await coordinator.getByRole('button', { name: /Report review/ }).click()
  await resident.evaluate(() => new Promise<void>(resolve => {
    const page = window as typeof window & { revisionMessages: string[]; revisionProbe?: EventSource }
    page.revisionMessages = []
    const events = new EventSource('/api/events'); page.revisionProbe = events
    events.addEventListener('open', () => resolve(), { once: true })
    events.addEventListener('revision', event => page.revisionMessages.push((event as MessageEvent).data))
  }))
  const id = 'ND-' + crypto.randomUUID().replaceAll('-', '').slice(0, 8).toUpperCase()
  const response = await resident.request.post('/api/actions', { headers: { 'Idempotency-Key': crypto.randomUUID() }, data: { type: 'submitReport', report: { id, type: 'shortage', town: 'Curepipe', condition: 'No running water', duration: '12–24 hours', households: 1, description: 'Private cross-session test report.' } } })
  expect(response.status()).toBe(200)
  await expect.poll(() => resident.evaluate(() => (window as typeof window & { revisionMessages: string[] }).revisionMessages.length), { timeout: 2500 }).toBeGreaterThan(0)
  const messages = await resident.evaluate(() => (window as typeof window & { revisionMessages: string[] }).revisionMessages)
  expect(messages.every(message => /^\d+$/.test(message))).toBe(true)
  await expect(coordinator.locator('.wf-subcard').filter({ hasText: id })).toBeVisible({ timeout: 2500 })
  const anonymous = await browser.newContext(); const publicResponse = await anonymous.request.get('http://127.0.0.1:4175/api/state')
  expect((await publicResponse.json()).state.reports).toEqual([])
  await anonymous.close(); await residentContext.close(); await coordinatorContext.close()
})
