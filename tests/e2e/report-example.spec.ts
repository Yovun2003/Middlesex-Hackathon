import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
test('reporting starts with the form, and the tap example can be shown and hidden',async({page},info)=>{
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('/#/user')
 await expect(page.getByRole('heading',{name:'Tell us what you’re seeing.'})).toBeVisible()
 await expect(page.getByText('Display options',{exact:true})).toHaveCount(0)
 await expect(page.locator('.persistent-world')).toBeHidden()
 await page.getByRole('button',{name:'Show example',exact:true}).click()
 await expect(page.getByText('Normal flow: water moves freely',{exact:true})).toBeVisible()
 await expect(page.locator('[data-world-canvas]')).toHaveAttribute('data-xray-flow','strong')
 await page.screenshot({path:info.outputPath('xray-normal-flow.png')})
 await page.getByRole('button',{name:'Hide example',exact:true}).click()
 await page.getByRole('combobox',{name:'What are you seeing?',exact:true}).selectOption('No running water')
 await page.getByRole('button',{name:'Show example',exact:true}).click()
 await expect(page.getByText('No water: the tap stays dry',{exact:true})).toBeVisible()
 await expect(page.locator('[data-world-canvas]')).toHaveAttribute('data-tap-flow','0.00')
 await page.screenshot({path:info.outputPath('dry-tap-example.png')})
 await page.getByRole('button',{name:'Hide example',exact:true}).click()
 await expect(page.locator('.persistent-world')).toBeHidden()
 await page.getByRole('combobox',{name:'What are you seeing?',exact:true}).selectOption('Low pressure')
 await page.getByRole('button',{name:'Show example',exact:true}).click()
 await expect(page.getByText('Low pressure: a weak stream',{exact:true})).toBeVisible()
 await expect(page.locator('[data-world-canvas]')).toHaveAttribute('data-tap-flow','0.20')
 await page.setViewportSize({width:390,height:844})
 await page.getByRole('button',{name:'Hide example',exact:true}).click()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 const audit=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa']).analyze();expect(audit.violations.map(v=>v.id)).toEqual([])
 await page.screenshot({path:info.outputPath('report-form-mobile.png')})
})

test('water moves through the connected pipe and stops with no supply or reduced motion',async({page})=>{
 await page.goto('/#/user')
 await page.getByRole('button',{name:'Show example',exact:true}).click()
 const canvas=page.locator('[data-world-canvas]')
 await expect(canvas).toHaveAttribute('data-xray-flow','strong')
 const first=await canvas.getAttribute('data-xray-progress')
 await expect.poll(()=>canvas.getAttribute('data-xray-progress')).not.toBe(first)
 await page.getByRole('combobox',{name:'What are you seeing?',exact:true}).selectOption('Low pressure')
 await expect(canvas).toHaveAttribute('data-tap-flow','0.20')
 await expect(canvas).toHaveAttribute('data-xray-flow','low')
 await page.getByRole('combobox',{name:'What are you seeing?',exact:true}).selectOption('No running water')
 await expect(canvas).toHaveAttribute('data-tap-flow','0.00')
 await expect(canvas).toHaveAttribute('data-xray-flow','stopped')
 await page.waitForTimeout(200)
 const stopped=await canvas.getAttribute('data-xray-progress');await page.waitForTimeout(350)
 expect(await canvas.getAttribute('data-xray-progress')).toBe(stopped)
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.getByRole('combobox',{name:'What are you seeing?',exact:true}).selectOption('')
 await expect(canvas).toHaveAttribute('data-xray-flow','strong')
 const reduced=await canvas.getAttribute('data-xray-progress');await page.waitForTimeout(350)
 expect(await canvas.getAttribute('data-xray-progress')).toBe(reduced)
})
