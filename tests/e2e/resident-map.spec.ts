import {test,expect} from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('resident can pin a problem, save it privately, browse public updates and return home',async({page},info)=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('/')
 await expect(page.getByText('Map & asset credits',{exact:true})).toHaveCount(0)
 await expect(page.getByText('Explore the neighbourhood',{exact:true})).toHaveCount(0)
 await page.getByRole('link',{name:'Water problems map',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Water problems in Mauritius'})).toBeVisible()
 await page.getByRole('combobox',{name:'Show',exact:true}).selectOption('all')
 await page.getByRole('link',{name:'NouDilo home'}).click()
 await expect(page.getByRole('heading',{name:'Report a water problem.'})).toBeVisible()
 await page.getByRole('button',{name:'Report a water issue'}).click()
 await page.getByRole('link',{name:'NouDilo home'}).click()
 await expect(page.getByRole('button',{name:'Close reporting panel'})).toHaveCount(0)
 await page.locator('.demo-roles summary').click()
 await page.locator('.demo-roles').getByRole('button',{name:'Resident',exact:true}).click()
 await page.getByRole('button',{name:'Continue shortage report'}).click()
 const dialog=page.locator('dialog[open]')
 await dialog.getByRole('combobox',{name:'Town or village',exact:true}).selectOption('Grand Baie')
 await dialog.getByRole('button',{name:'Choose location on map'}).click()
 await dialog.getByRole('button',{name:'Use centre of map'}).click({timeout:25000})
 await expect(dialog.getByText('Location selected',{exact:false})).toBeVisible()
 await dialog.getByRole('button',{name:'Close location map'}).click()
 await dialog.getByRole('combobox',{name:'What are you experiencing?',exact:true}).selectOption('No running water')
 await dialog.getByRole('combobox',{name:'How long?',exact:true}).selectOption('Under 12 hours')
 await dialog.getByRole('button',{name:'Review report',exact:true}).click()
 await dialog.getByRole('button',{name:'Send report',exact:true}).click()
 await expect(dialog.getByRole('heading',{name:'Report received',exact:true})).toBeVisible()
 let saved=(await(await page.request.get('/api/state')).json()).state.reports.find((r:{coordinates?:unknown})=>r.coordinates)
 expect(saved.coordinates.latitude).toBeGreaterThan(-20.6);expect(saved.coordinates.longitude).toBeGreaterThan(57.25)
 await dialog.getByRole('button',{name:'Done',exact:true}).click()
 await page.reload()
 const refreshed=(await(await page.request.get('/api/state')).json()).state.reports.find((r:{id:string})=>r.id===saved.id)
 expect(refreshed.coordinates).toEqual(saved.coordinates)
 await page.locator('.demo-roles summary').click();await page.locator('.demo-roles').getByRole('button',{name:'Coordinator',exact:true}).click()
 const result=await page.request.post('/api/actions',{headers:{'Idempotency-Key':crypto.randomUUID()},data:{type:'verifyReport',reportId:saved.id,estimatedLitres:1500}})
 expect(result.ok()).toBe(true)
 await page.getByRole('link',{name:'Water problems map',exact:true}).click()
 await expect(page.locator('.task-scroll')).toContainText('Grand Baie')
 await page.getByRole('combobox',{name:'Show',exact:true}).selectOption('leak')
 await expect(page.locator('.task-scroll')).not.toContainText('Grand Baie')
 await page.request.post('/api/logout')
 await page.goto('/')
 const publicData=(await(await page.request.get('/api/state')).json()).state
 expect(publicData.reports).toEqual([])
 await page.getByRole('link',{name:'Water problems map',exact:true}).click()
 await page.getByRole('combobox',{name:'Show',exact:true}).selectOption('all')
 await expect(page.locator('.task-scroll')).toContainText('Grand Baie')
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 const audit=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa']).analyze();expect(audit.violations.map(v=>({id:v.id,targets:v.nodes.map(n=>n.target)}))).toEqual([])
 await page.screenshot({path:info.outputPath('resident-public-map-mobile.png')})
 expect(errors).toEqual([])
})
